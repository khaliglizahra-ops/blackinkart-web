export type UIKey = keyof (typeof ui)['tr'];

/**
 * Çevirmen. Eksik anahtarda Türkçesine düşüyor — İngilizce sayfa yarım
 * kalmasın diye. Eksikleri `npm run i18n:check` listeler.
 */
export function useTranslations(lang: Lang) {
  return function t(key: UIKey): string {
    const table = ui[lang] as Record<string, string>;
    return table[key] ?? (ui.tr as Record<string, string>)[key] ?? key;
  };
}
